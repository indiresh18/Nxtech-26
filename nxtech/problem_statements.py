def get_problem_statement_choices():
    """Returns a list of (code, display_text) tuples for forms & dropdowns."""
    return [
        (
            item["ps_id"],
            f"[{item['ps_id']}] {item['title']} ({item['category']} | {item['stream']})"
        )
        for item in HACKATHON_PROBLEM_STATEMENTS
    ]


def generate_hackathon_pdf_bytes():
    """
    Generates a beautifully formatted PDF document containing all 30
    NxTech'26 Hackathon problem statements.
    """
    import io
    from reportlab.lib.pagesizes import letter
    from reportlab.platypus import SimpleDocTemplate, Paragraph, Table, TableStyle, Spacer
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.lib import colors

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=32,
        rightMargin=32,
        topMargin=32,
        bottomMargin=32
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        'DocTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=15,
        leading=19,
        textColor=colors.HexColor('#0F172A'),
        alignment=1  # Center
    )
    subtitle_style = ParagraphStyle(
        'DocSubtitle',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#64748B'),
        alignment=1
    )
    th_style = ParagraphStyle(
        'TH',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=11,
        textColor=colors.white,
        alignment=1
    )
    id_style = ParagraphStyle(
        'CellID',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=11,
        textColor=colors.HexColor('#7C1A7E'),
        alignment=1
    )
    title_in_cell = ParagraphStyle(
        'CellTitle',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=9,
        leading=12,
        textColor=colors.HexColor('#0F172A')
    )
    desc_in_cell = ParagraphStyle(
        'CellDesc',
        parent=styles['Normal'],
        fontName='Helvetica',
        fontSize=7.5,
        leading=10,
        textColor=colors.HexColor('#475569')
    )
    badge_style = ParagraphStyle(
        'Badge',
        parent=styles['Normal'],
        fontName='Helvetica-Bold',
        fontSize=8,
        leading=10,
        textColor=colors.HexColor('#334155'),
        alignment=1
    )

    story = []
    # Header Banner
    story.append(Paragraph("<b>STUDENT RESEARCH COUNCIL (SRC)</b>", title_style))
    story.append(Paragraph("Dr. Mahalingam College of Engineering & Technology, Pollachi", subtitle_style))
    story.append(Spacer(1, 4))
    story.append(Paragraph("<b>NxTech 2K26 Hackathon — Official Problem Statements</b>", ParagraphStyle(
        'BannerSub', parent=title_style, fontSize=11, leading=14, textColor=colors.HexColor('#7C1A7E')
    )))
    story.append(Paragraph("Exclusively for First-Year Students • Fixed 5 Members Squad • 6-Hour Innovation Sprint", subtitle_style))
    story.append(Spacer(1, 10))

    # Table Header
    headers = [
        Paragraph("PS ID", th_style),
        Paragraph("Problem Statement & Description", th_style),
        Paragraph("Type", th_style),
        Paragraph("Stream", th_style),
    ]
    data = [headers]

    for item in HACKATHON_PROBLEM_STATEMENTS:
        content_p = [
            Paragraph(f"<b>{item['title']}</b>", title_in_cell),
            Spacer(1, 2),
            Paragraph(item['description'], desc_in_cell)
        ]
        row = [
            Paragraph(f"<b>{item['ps_id']}</b>", id_style),
            content_p,
            Paragraph(item['category'], badge_style),
            Paragraph(item['stream'], badge_style),
        ]
        data.append(row)

    col_widths = [45, 365, 68, 62]  # Sum = 540 pt
    t = Table(data, colWidths=col_widths, repeatRows=1)
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#4A154B')),
        ('ALIGN', (0, 0), (-1, 0), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('LEFTPADDING', (0, 0), (-1, -1), 4),
        ('RIGHTPADDING', (0, 0), (-1, -1), 4),
        ('GRID', (0, 0), (-1, -1), 0.5, colors.HexColor('#E2E8F0')),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#F8FAFC')]),
    ]))

    story.append(t)
    doc.build(story)
    buffer.seek(0)
    return buffer.getvalue()

